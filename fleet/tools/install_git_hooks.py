def _configure_git_branch_protection(repo_root: Path) -> None:
    """Applies local Git configuration settings that protect the main branch."""
    git_exe = "git"
    fallback_git = Path(os.path.expanduser(r"~\AppData\Local\Programs\Git\cmd\git.exe"))
    if fallback_git.is_file():
        git_exe = str(fallback_git)
    settings = [
        ("receive.denyDeletes", "true"),
        ("receive.denyNonFastForwards", "true"),
        ("branch.main.mergeOptions", "--no-ff"),
        ("user.name", "macazaka"),
        ("user.email", "102894891+macazaka@users.noreply.github.com"),
    ]
    for key, val in settings:
        try:
            if os.name == "nt":
                subprocess.run(
                    [git_exe, "-C", str(repo_root), "config", key, val],
                    capture_output=True,
                    timeout=5,
                    check=False,
                    creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0x08000000),
                )
            else:
                subprocess.run(
                    [git_exe, "-C", str(repo_root), "config", key, val],
                    capture_output=True,
                    timeout=5,
                    check=False,
                )
        except Exception:
            pass
            pass


def install_git_hooks(repo_root: Path = ROOT_DIR) -> dict:
    """Installs pre-commit and pre-push security & branch-protection hooks into .git/hooks/."""
    hooks_dir = repo_root / ".git" / "hooks"
    if not hooks_dir.exists():
        return {"status": "skipped", "reason": ".git/hooks directory not found"}

    _configure_git_branch_protection(repo_root)

    python_shebang = sys.executable.replace("\\", "/") if sys.executable else "/usr/bin/env python"
    installed = []

    # Install pre-commit
    pre_commit_path = hooks_dir / "pre-commit"
    pre_commit_path.write_text(PRE_COMMIT_TEMPLATE.format(python_shebang=python_shebang), encoding="utf-8", newline="\n")
    try:
        pre_commit_path.chmod(pre_commit_path.stat().st_mode | stat.S_IEXEC)
    except Exception:
        pass
    installed.append(str(pre_commit_path))

    # Install pre-push
    pre_push_path = hooks_dir / "pre-push"
    pre_push_path.write_text(PRE_PUSH_TEMPLATE.format(python_shebang=python_shebang), encoding="utf-8", newline="\n")
    try:
        pre_push_path.chmod(pre_push_path.stat().st_mode | stat.S_IEXEC)
    except Exception:
        pass
    installed.append(str(pre_push_path))

    return {"status": "installed", "hooks": installed, "main_branch_protected": True, "preflight_gate_active": True}


if __name__ == "__main__":
    res = install_git_hooks()
    print(f"Git Security, CI & Main Branch Protection Hooks: {res['status']} -> {res.get('hooks', [])}")
    sys.exit(0)
